def build_normal_text(topic: dict) -> str:
    """Assemble the benign document body from a topic's sections."""
    lines = [topic["title"], ""]
    for heading, body in topic["sections"]:
        lines.append(heading)
        lines.append(body)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def normal_tail(topic: dict) -> str:
    """A benign tail (last 3 sections) appended after attack prefixes/payloads."""
    lines = []
    for heading, body in topic["sections"][-3:]:
        lines.append(heading)
        lines.append(body)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


